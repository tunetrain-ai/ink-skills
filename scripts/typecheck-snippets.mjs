#!/usr/bin/env node
// Compiles every ```tsx / ```jsx fence in SKILL.md and references/*.md against the real
// installed packages. This is what catches hallucinated props and API drift in a docs-derived
// catalog.
//
// Two projects, chosen by what a fence imports:
//   root      — packages in this repo's own devDependencies           → .snippets/
//   external  — packages only in tests/external (peer-excluded, broken CommonJS, react-router,
//               meow, ...), which cannot be installed next to Ink 8      → tests/external/.snippets/
// Routing is by DECLARED dependency, not by "does it resolve", so it does not depend on whether
// tests/external happens to be installed on this machine (it must be, when a fence needs it).
//
// Placeholder imports in a fence ("./app.js" standing in for the reader's own component) are
// satisfied by tests/fence-stubs.json — the skill text stays copy-pasteable.
//
// A legacy ```tsx no-check tag is still honoured (and reported) but is being removed: shipped
// skill text should not carry tooling flags.

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';
import { ROOT, discoverSkillFiles, extractFences } from './lib/skills.mjs';
import { referenceFiles } from './lib/skills.mjs';

const TSC = join(ROOT, 'node_modules', '.bin', 'tsc');
const ROOT_SNIPPETS = join(ROOT, '.snippets');
const EXT_DIR = join(ROOT, 'tests', 'external');
const EXT_SNIPPETS = join(EXT_DIR, '.snippets');

const HEADER = `// AUTO-GENERATED by scripts/typecheck-snippets.mjs — do not edit.
// Extracted verbatim from a \`\`\`tsx fence to verify it compiles against real ink/react
// types. Snippets must bring their own imports, same as real copy-pasted code would.
`;

const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));
const rootPkg = await readJson(join(ROOT, 'package.json'));
const extPkg = await readJson(join(EXT_DIR, 'package.json'));
const rootDeps = new Set([...Object.keys(rootPkg.dependencies ?? {}), ...Object.keys(rootPkg.devDependencies ?? {})]);
const externalOnly = new Set(Object.keys(extPkg.dependencies ?? {}).filter((name) => !rootDeps.has(name)));
const stubsPath = join(ROOT, 'tests', 'fence-stubs.json');
const stubs = existsSync(stubsPath) ? await readJson(stubsPath) : {};
const builtins = new Set([...builtinModules, ...builtinModules.map((m) => `node:${m}`)]);

/** Bare package name of an import specifier ("@a/b/c" → "@a/b", "x/y" → "x"). */
function packageName(specifier) {
  const parts = specifier.split('/');
  return specifier.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

function importedPackages(code) {
  const names = new Set();
  for (const m of code.matchAll(/(?:from|import|require)\s*\(?\s*['"]([^'"]+)['"]/g)) {
    if (m[1].startsWith('.') || builtins.has(m[1])) continue;
    names.add(packageName(m[1]));
  }
  return names;
}

async function main() {
  for (const dir of [ROOT_SNIPPETS, EXT_SNIPPETS]) await rm(dir, { recursive: true, force: true });
  await mkdir(ROOT_SNIPPETS, { recursive: true });

  const skills = await discoverSkillFiles();
  const counts = { root: 0, external: 0, legacySkipped: 0 };
  const legacyByFile = new Map();
  const usedStubs = { root: new Set(), external: new Set() };

  for (const skill of skills) {
    const sources = [{ path: skill.skillMdPath, markdown: skill.body }, ...(await referenceFiles(skill.dir))];
    for (const source of sources) {
      const fences = extractFences(source.markdown);
      const relLabel = relative(ROOT, source.path).replace(/[\\/]/g, '__').replace(/\.md$/, '');
      for (let i = 0; i < fences.length; i++) {
        const fence = fences[i];
        if (fence.lang !== 'tsx' && fence.lang !== 'jsx') continue;
        if (fence.noCheck) {
          counts.legacySkipped++;
          const rel = relative(ROOT, source.path);
          legacyByFile.set(rel, (legacyByFile.get(rel) ?? 0) + 1);
          continue;
        }
        const project = [...importedPackages(fence.code)].some((name) => externalOnly.has(name)) ? 'external' : 'root';
        counts[project]++;
        const dir = project === 'external' ? EXT_SNIPPETS : ROOT_SNIPPETS;
        await mkdir(dir, { recursive: true });
        // Force module isolation for snippets with no import/export of their own so unrelated
        // snippets' top-level `const`s can't collide in the shared global scope.
        const isModule = /^\s*(import|export)\b/m.test(fence.code);
        let code = isModule ? fence.code : `${fence.code}\nexport {};\n`;
        let prefix = HEADER;
        const shebang = code.match(/^#!.*\r?\n/);
        if (shebang) {
          code = code.slice(shebang[0].length);
          prefix = shebang[0] + HEADER;
        }
        await writeFile(join(dir, `${relLabel}__${i}.tsx`), prefix + code, 'utf8');
        for (const [specifier, source] of Object.entries(stubs)) {
          if (code.includes(`'${specifier}'`) || code.includes(`"${specifier}"`)) {
            // "./app.js" resolves to app.tsx next to the snippet
            const file = specifier.replace(/^\.\//, '').replace(/\.js$/, '.tsx');
            await writeFile(join(dir, file), source, 'utf8');
            usedStubs[project].add(specifier);
          }
        }
      }
    }
  }

  console.log(
    `Extracted ${counts.root + counts.external} snippet(s) (${counts.root} root, ${counts.external} external; ` +
      `${counts.legacySkipped} legacy no-check skipped) from ${skills.length} skill(s).`,
  );
  if (legacyByFile.size > 0) {
    console.log('Legacy no-check fences (not verified; the tag is being removed from skill text):');
    for (const [file, count] of [...legacyByFile].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) {
      console.log(`  ${String(count).padStart(2)}  ${file}`);
    }
  }

  const runs = [];
  if (counts.root) runs.push({ label: 'root', tsconfig: join(ROOT, 'tsconfig.json') });
  if (counts.external) {
    if (!existsSync(join(EXT_DIR, 'node_modules', 'ink'))) {
      console.error('\n✗ Some snippets need packages from tests/external, which is not installed — run `npm run test:setup`.');
      process.exit(1);
    }
    runs.push({ label: 'external', tsconfig: join(EXT_DIR, 'tsconfig.fences.json') });
  }
  if (runs.length === 0) {
    console.log('Nothing to typecheck.');
    return;
  }

  for (const run of runs) {
    const result = spawnSync(TSC, ['--noEmit', '-p', run.tsconfig], { cwd: ROOT, stdio: 'inherit' });
    if (result.status !== 0) {
      console.error(`\n✗ ${run.label} snippet typecheck failed — see tsc output above.`);
      console.error(`  Generated files are under ${relative(ROOT, run.label === 'root' ? ROOT_SNIPPETS : EXT_SNIPPETS)}/ for inspection.`);
      process.exit(result.status ?? 1);
    }
  }
  console.log('✓ All snippets typecheck cleanly against the installed packages.');
}

await main();
