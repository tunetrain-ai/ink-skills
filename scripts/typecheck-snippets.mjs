#!/usr/bin/env node
// Extracts every ```tsx / ```jsx fence from SKILL.md and references/*.md,
// writes them into .snippets/, and runs `tsc --noEmit` against the real
// ink / react / @inkjs/ui versions declared in devDependencies. This is what
// catches hallucinated props and API drift in a docs-derived catalog.
//
// A fence tagged ```tsx no-check is intentionally partial (e.g. shows a hook
// signature without a full component) and is skipped.

import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';
import { ROOT, discoverSkillFiles, extractCodeFences } from './lib/skills.mjs';

const SNIPPETS_DIR = join(ROOT, '.snippets');

const HEADER = `// AUTO-GENERATED by scripts/typecheck-snippets.mjs — do not edit.
// Extracted verbatim from a \`\`\`tsx fence to verify it compiles against real ink/react
// types. Snippets must bring their own imports, same as real copy-pasted code would.
`;

async function referenceMarkdownFiles(skillDir) {
  const refsDir = join(skillDir, 'references');
  let entries;
  try {
    entries = await readdir(refsDir, { withFileTypes: true });
  } catch {
    return [];
  }
  return Promise.all(
    entries
      .filter((e) => e.isFile() && e.name.endsWith('.md'))
      .map(async (e) => {
        const path = join(refsDir, e.name);
        return { path, markdown: await readFile(path, 'utf8') };
      })
  );
}

async function main() {
  await rm(SNIPPETS_DIR, { recursive: true, force: true });
  await mkdir(SNIPPETS_DIR, { recursive: true });

  const skills = await discoverSkillFiles();
  let fenceCount = 0;
  let skipCount = 0;

  for (const skill of skills) {
    const sources = [
      { path: skill.skillMdPath, markdown: skill.body },
      ...(await referenceMarkdownFiles(skill.dir)),
    ];

    for (const source of sources) {
      const fences = extractCodeFences(source.markdown);
      const relLabel = relative(ROOT, source.path)
        .replace(/[\\/]/g, '__')
        .replace(/\.md$/, '');

      for (let i = 0; i < fences.length; i++) {
        const fence = fences[i];
        if (fence.noCheck) {
          skipCount++;
          continue;
        }
        fenceCount++;
        const outPath = join(SNIPPETS_DIR, `${relLabel}__${i}.tsx`);
        // Force module isolation for snippets with no import/export of their own
        // (e.g. a short fragment shown mid-explanation) so unrelated snippets'
        // top-level `const`s can't collide in the shared global scope.
        const isModule = /^\s*(import|export)\b/m.test(fence.code);
        let code = isModule ? fence.code : `${fence.code}\nexport {};\n`;
        // A CLI entry-point shebang must be the literal first line of the file —
        // keep it there and put the header comment after it, not before.
        let prefix = HEADER;
        const shebangMatch = code.match(/^#!.*\r?\n/);
        if (shebangMatch) {
          code = code.slice(shebangMatch[0].length);
          prefix = shebangMatch[0] + HEADER;
        }
        await writeFile(outPath, prefix + code, 'utf8');
      }
    }
  }

  console.log(
    `Extracted ${fenceCount} snippet(s) (${skipCount} tagged no-check and skipped) ` +
      `from ${skills.length} skill(s).`
  );

  if (fenceCount === 0) {
    console.log('Nothing to typecheck.');
    return;
  }

  const result = spawnSync('npx', ['tsc', '--noEmit', '-p', join(ROOT, 'tsconfig.json')], {
    cwd: ROOT,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });

  if (result.status !== 0) {
    console.error('\n✗ Snippet typecheck failed — see tsc output above.');
    console.error(`  Generated files are under ${relative(ROOT, SNIPPETS_DIR)}/ for inspection.`);
    process.exit(result.status ?? 1);
  }

  console.log('✓ All snippets typecheck cleanly against ink/react/@inkjs/ui.');
}

await main();
